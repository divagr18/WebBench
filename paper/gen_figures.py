"""Generate print-quality figures for the EchoNet paper.

All numeric values are computed at build time from:
  - paper/paper_data.json (per-model metrics, generated by gen_paper_data.py)
  - paper/cross_field_data.json (pairwise/taxonomy/calibration, generated by
    cross_field.py)

Nothing here is hand-transcribed from analysis/cross_model_report.md any more
-- the taxonomy, AUC, and pairwise-vs-leader figures below previously came
from three hard-coded dicts that a pipeline rerun would never update; this
version reads their inputs from the same JSON gen_tables.py uses, so a rerun
regenerates every figure consistently with every table.

Outputs vector PDFs + 200dpi PNG previews into paper/figures/.
"""
