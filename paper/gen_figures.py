matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from matplotlib import font_manager

# ---------------------------------------------------------------- style
names = {f.name for f in font_manager.fontManager.ttflist}
serif = ["STIXGeneral"] if "STIXGeneral" in names else ["DejaVu Serif"]
plt.rcParams.update({
    "font.family": "serif",
    "font.serif": serif,
    "font.size": 9.0,
    "axes.labelsize": 9.0,
    "axes.titlesize": 9.5,
    "xtick.labelsize": 8.0,
    "ytick.labelsize": 8.0,
    "legend.fontsize": 7.5,
    "figure.dpi": 200,
    "savefig.bbox": "tight",
    "savefig.pad_inches": 0.02,
    "axes.linewidth": 0.6,
    "xtick.major.width": 0.5,
    "ytick.major.width": 0.5,
    "lines.linewidth": 1.1,
})

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "figures")
os.makedirs(OUT, exist_ok=True)
DATA = json.load(open(os.path.join(HERE, "paper_data.json"), encoding="utf-8"))
CROSS = json.load(open(os.path.join(HERE, "cross_field_data.json"), encoding="utf-8"))

# Field-only view, ordered by EAS descending (leaderboard order) -- matches gen_tables.py.
# Must be the SAME set cross_field.py's eligible() computed (CROSS["fieldModels"]), not a
# separate role=="field" re-filter -- see gen_tables.py's FIELD_KEYS comment for why.
_field_display_names = set(CROSS["fieldModels"])
MODEL_ORDER = sorted(
    (k for k, d in DATA.items() if d["displayName"] in _field_display_names),
    key=lambda k: DATA[k]["eas"], reverse=True,
)
DISPLAY = {k: DATA[k]["displayName"] for k in MODEL_ORDER}
SHORT = {k: DATA[k]["displayName"].replace("GPT-5.6 ", "").replace(" Spark 1.2", " Spark") for k in MODEL_ORDER}
N_RUNS = {k: DATA[k]["completedRuns"] for k in MODEL_ORDER}

C10 = plt.get_cmap("tab10").colors
COLORS = {k: C10[i % 10] for i, k in enumerate(MODEL_ORDER)}

COND_ORDER = ["clean", "single_poison", "ranked_poison", "manufactured_consensus",
              "legitimate_update", "false_majority_true_primary"]
COND_LABEL = {
    "clean": "clean",
    "single_poison": "single poison",
    "ranked_poison": "ranked poison",
    "manufactured_consensus": "manufactured\nconsensus",
    "legitimate_update": "legitimate\nupdate",
    "false_majority_true_primary": "false majority,\ntrue primary",
}


def save(fig, name):
    fig.savefig(os.path.join(OUT, name + ".pdf"))
    fig.savefig(os.path.join(OUT, name + ".png"), dpi=200)
    plt.close(fig)
    print("wrote", name)


def pareto_frontier(points):
    """points: [(key, cost, eas)] -> the Pareto-efficient subset (min cost, max eas),
    sorted by cost. Actually computed, not a hand-picked literal list."""
    pts = sorted(points, key=lambda p: p[1])
    frontier = []
    best_eas = -1.0
    for key, cost, eas in pts:
        if eas > best_eas:
            frontier.append((key, cost, eas))
            best_eas = eas
    return frontier


# ------------------------------------------------ F3: accuracy by condition
fig, ax = plt.subplots(figsize=(5.5, 2.75))
for k in MODEL_ORDER:
    accs = [DATA[k]["conditions"][c]["acc"] for c in COND_ORDER]
    ax.plot(range(len(COND_ORDER)), accs, marker="o", markersize=2.6,
            color=COLORS[k], label=SHORT[k], zorder=3)
# Shade whichever condition(s) currently separate the field most, computed fresh each
# build rather than hand-picked -- which condition(s) this is has already changed once
# as the field grew (false-majority alone -> manufactured-consensus and false-majority),
# so a hardcoded index would silently go stale the same way the prose around this figure
# already did once.
_spreads = {
    i: max(DATA[k]["conditions"][c]["acc"] for k in MODEL_ORDER) - min(DATA[k]["conditions"][c]["acc"] for k in MODEL_ORDER)
    for i, c in enumerate(COND_ORDER)
}
_shade_threshold = 0.30
for i, spread in _spreads.items():
    if spread >= _shade_threshold:
        ax.axvspan(i - 0.5, i + 0.5, color="0.93", zorder=0)
ax.set_xticks(range(len(COND_ORDER)))
ax.set_xticklabels([COND_LABEL[c] for c in COND_ORDER])
ax.set_ylabel("Accuracy")
ax.set_ylim(0.42, 1.02)
ax.grid(axis="y", color="0.88", linewidth=0.5)
ax.set_axisbelow(True)
ax.legend(ncols=3, loc="upper center", bbox_to_anchor=(0.5, -0.34), frameon=False,
          handlelength=1.2, columnspacing=1.0)
save(fig, "fig_conditions")

# ------------------------------------------------ F4: resistance vs update
fig, ax = plt.subplots(figsize=(5.5, 3.1))
xs = np.linspace(0.0, 1.0, 400)
ys = np.linspace(0.0, 1.0, 400)
X, Y = np.meshgrid(xs, ys)
with np.errstate(divide="ignore", invalid="ignore"):
    EAS = np.where(X + Y > 0, 2 * X * Y / (X + Y), 0)
cs = ax.contour(X, Y, EAS, levels=[0.70, 0.80, 0.85, 0.90, 0.95],
                colors="0.75", linewidths=0.6, linestyles="--", zorder=1)
ax.clabel(cs, inline=True, fontsize=6.5, fmt="%.2f")
for k in MODEL_ORDER:
    cur = DATA[k]["cur"]
    res = 1.0 - DATA[k]["fbar"]
    ax.scatter(cur, res, color=COLORS[k], s=26, zorder=3)
    ax.annotate(SHORT[k], (cur, res), textcoords="offset points", xytext=(4, 3), fontsize=6.8, zorder=3)
ax.set_xlim(0.60, 1.035)
ax.set_ylim(0.75, 1.02)
ax.set_xlabel("Correct update rate (CUR)")
ax.set_ylabel("Corruption resistance (1 - FBAR)")
ax.text(0.712, 0.997, "trust memory only", fontsize=6.8, color="0.45", style="italic")
ax.text(0.965, 0.832, "trust web only", fontsize=6.8, color="0.45", style="italic", ha="right")
save(fig, "fig_arbitration")

# ------------------------------------------------ F5: cost vs EAS
fig, ax = plt.subplots(figsize=(5.5, 3.0))
pts = {}
for k in MODEL_ORDER:
    cost_per_episode = DATA[k]["cost"] / N_RUNS[k]
    pts[k] = (cost_per_episode, DATA[k]["eas"])
    ax.scatter(cost_per_episode, DATA[k]["eas"], color=COLORS[k], s=26, zorder=3)
    ax.annotate(SHORT[k], (cost_per_episode, DATA[k]["eas"]), textcoords="offset points",
                xytext=(4, 3), fontsize=6.8, zorder=3)
front = pareto_frontier([(k, c, e) for k, (c, e) in pts.items()])
fx = [c for _, c, _ in front]
fy = [e for _, _, e in front]
if fx:
    x_max = max(c for c, _ in pts.values()) * 1.4
    ax.step(fx + [x_max], fy + [fy[-1]], where="post", color="0.55", linewidth=0.8,
            linestyle=":", zorder=2)
    print("cost Pareto frontier:", [(k, round(c, 4), round(e, 4)) for k, c, e in front])
ax.set_xscale("log")
ax.set_xlabel("Estimated API cost per episode (USD, list pricing)")
ax.set_ylabel("Epistemic Arbitration Score (EAS)")
all_costs = [c for c, _ in pts.values()]
ax.set_xlim(min(all_costs) * 0.7, max(all_costs) * 2.0)
ax.set_ylim(min(e for _, e in pts.values()) - 0.05, 1.00)
ax.grid(axis="y", color="0.88", linewidth=0.5)
ax.set_axisbelow(True)
save(fig, "fig_cost")

# ------------------------------------------------ F6: failure taxonomy (from cross_field_data.json)
TAX = {n: t for n, t in CROSS["taxonomy"].items()}
CATS = ["correct and stable", "rescued", "corrupted", "stuck wrong"]
CAT_COLORS = ["#1f77b4", "#2ca02c", "#d62728", "#7f7f7f"]
if TAX:
    fig, ax = plt.subplots(figsize=(5.5, 0.9 + 0.32 * len(TAX)))
    ys = np.arange(len(TAX))[::-1]
    lefts = np.zeros(len(TAX))
    tots = np.array([t["rescued"] + t["corrupted"] + t["stuckWrong"] + t["correctStable"] for t in TAX.values()])
    for ci, cat in enumerate(CATS):
        field = {"rescued": "rescued", "corrupted": "corrupted", "stuck wrong": "stuckWrong", "correct and stable": "correctStable"}[cat]
        vals = np.array([TAX[m][field] for m in TAX])
        fr = np.divide(vals, tots, out=np.zeros_like(vals, dtype=float), where=tots != 0)
        ax.barh(ys, fr, left=lefts, color=CAT_COLORS[ci], label=cat, height=0.62,
                edgecolor="white", linewidth=0.4)
        lefts += fr
    ax.set_yticks(ys)
    ax.set_yticklabels(list(TAX), fontsize=7.5)
    ax.set_xlim(0, 1)
    ax.set_xlabel("Fraction of scored episodes")
    ax.legend(ncols=4, loc="upper center", bbox_to_anchor=(0.5, -0.22), frameon=False,
              handlelength=1.1, columnspacing=1.0)
    save(fig, "fig_taxonomy")
else:
    print("skipping fig_taxonomy: no field models in cross_field_data.json")

# ------------------------------------------------ F7: reliability grid
AUC = {c["model"]: c["auc"] for c in CROSS["calibration"] if c["auc"] is not None}
n_panels = len(MODEL_ORDER)
n_cols = 4
n_rows = max(1, (n_panels + n_cols - 1) // n_cols)
fig, axes = plt.subplots(n_rows, n_cols, figsize=(5.5, 1.55 * n_rows + 0.3))
axes = np.atleast_1d(axes).ravel()
for i, k in enumerate(MODEL_ORDER):
    ax = axes[i]
    d = DATA[k]
    ax.plot([0, 1], [0, 1], color="0.7", linewidth=0.6)
    for b in d["bins"]:
        c = b["avgConfidence"]
        acc = b["accuracy"]
        ax.bar(c, acc, width=0.075, color=COLORS[k], alpha=0.85, edgecolor="white", linewidth=0.3)
    ax.set_xlim(0.45, 1.0)
    ax.set_ylim(0, 1)
    ax.set_xticks([0.5, 0.75, 1.0])
    ax.set_yticks([0, 0.5, 1.0])
    ax.tick_params(labelsize=5.8, length=2)
    disp = DISPLAY[k]
    auc_label = f"AUC {AUC[disp]:.2f}, " if disp in AUC else ""
    ax.set_title(f"{SHORT[k]}\n{auc_label}ECE {d['ece']:.2f}", fontsize=6.6, pad=2)
for ax in axes[n_panels:]:
    ax.axis("off")
if n_panels > 0:
    axes[min(2, n_panels - 1)].set_xlabel("Confidence", fontsize=7)
    axes[0].set_ylabel("Accuracy", fontsize=7)
fig.tight_layout(pad=0.6, h_pad=0.9)
save(fig, "fig_calibration")

# ------------------------------------------------ F8: paired differences vs the shared-episode accuracy leader
vs_leader = CROSS["pairwise"]["vsLeader"]
if vs_leader:
    fig, ax = plt.subplots(figsize=(5.5, 0.5 + 0.32 * len(vs_leader)))
    ys = np.arange(len(vs_leader))[::-1]
    for y, r in zip(ys, vs_leader):
        col = "#1f77b4" if r["significant"] else "0.72"
        d, lo, hi = r["diff"], r["lo"], r["hi"]
        ax.errorbar(d, y, xerr=[[d - lo], [hi - d]], fmt="none", ecolor=col,
                    elinewidth=1.0, capsize=2.5, capthick=1.0, zorder=2)
        ax.scatter(d, y, s=20, color=col, zorder=3)
    ax.axvline(0.0, color="0.5", linewidth=0.7)
    ax.set_yticks(ys)
    ax.set_yticklabels([r["b"] for r in vs_leader], fontsize=7.5)
    span = max(abs(r["lo"]) for r in vs_leader + [{"lo": 0.05}]) if vs_leader else 0.05
    ax.set_xlim(-span * 1.3, span * 1.3 + 0.05)
    ax.set_xlabel(f"Accuracy difference vs. {CROSS['leader']}\n(95% claim-clustered bootstrap CI, Holm-corrected)", fontsize=8)
    save(fig, "fig_pairwise")
else:
    print("skipping fig_pairwise: no vs-leader comparisons in cross_field_data.json")

