"""Generate print-quality figures for the EchoNet paper.

All numeric values come from the frozen pilot data:
  - D:/WebBench/analysis/data_model_comparison.json (generated by gen_dashboard_data.py)
  - D:/WebBench/analysis/cross_model_report.md tables 1, 3, 4 (hardcoded below with source comments)

Outputs vector PDFs + 200dpi PNG previews into paper/figures/.
"""
import json
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from matplotlib import font_manager

# ---------------------------------------------------------------- style
names = {f.name for f in font_manager.fontManager.ttflist}
serif = ["STIXGeneral"] if "STIXGeneral" in names else ["DejaVu Serif"]
plt.rcParams.update({
    "font.family": "serif",
    "font.serif": serif,
    "font.size": 9.0,
    "axes.labelsize": 9.0,
    "axes.titlesize": 9.5,
    "xtick.labelsize": 8.0,
    "ytick.labelsize": 8.0,
    "legend.fontsize": 7.5,
    "figure.dpi": 200,
    "savefig.bbox": "tight",
    "savefig.pad_inches": 0.02,
    "axes.linewidth": 0.6,
    "xtick.major.width": 0.5,
    "ytick.major.width": 0.5,
    "lines.linewidth": 1.1,
})

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "figures")
os.makedirs(OUT, exist_ok=True)
DATA = json.load(open(os.path.join(HERE, "paper_data.json"), encoding="utf-8"))

# tab10, fixed assignment per model
C10 = plt.get_cmap("tab10").colors
MODEL_ORDER = [  # leaderboard order, 11 configs
    "gemini-3.7-fl", "qwen3.7-max", "gpt-5.6-luna", "gpt-5.6-terra", "muse",
    "qwen3.7-plus", "gpt-5.6-sol", "gemini-3.5-lite", "grok", "deepseek-chat",
]
SHORT = {
    "deepseek-chat": "DeepSeek V4 Flash",
    "gpt-5.6-luna": "GPT-5.6 Luna",
    "qwen3.7-max": "Qwen3.7 Max",
    "qwen3.7-plus": "Qwen3.7 Plus",
    "gemini-3.7-fl": "Gemini 3.7 Flash",
    "gemini-3.5-lite": "Gemini 3.5 Flash-Lite",
    "gpt-5.6-terra": "GPT-5.6 Terra",
    "muse": "Muse Spark 1.2",
    "grok": "Grok 4.6",
    "gpt-5.6-sol": "GPT-5.6 Sol",
}
N_RUNS = {  # completed runs per pilot (README / PREREG)
    "deepseek-chat": 100, "gpt-5.6-luna": 100, "qwen3.7-max": 100,
    "qwen3.7-plus": 100, "gemini-3.7-fl": 100, "gemini-3.5-lite": 100,
    "gpt-5.6-terra": 80, "muse": 80, "grok": 80, "gpt-5.6-sol": 50,
}
COLORS = {k: C10[i % 10] for i, k in enumerate(MODEL_ORDER)}

COND_ORDER = ["clean", "single_poison", "ranked_poison", "manufactured_consensus",
              "legitimate_update", "false_majority_true_primary"]
COND_LABEL = {
    "clean": "clean",
    "single_poison": "single poison",
    "ranked_poison": "ranked poison",
    "manufactured_consensus": "manufactured\nconsensus",
    "legitimate_update": "legitimate\nupdate",
    "false_majority_true_primary": "false majority,\ntrue primary",
}


def save(fig, name):
    fig.savefig(os.path.join(OUT, name + ".pdf"))
    fig.savefig(os.path.join(OUT, name + ".png"), dpi=200)
    plt.close(fig)
    print("wrote", name)


# ------------------------------------------------ F3: accuracy by condition
fig, ax = plt.subplots(figsize=(5.5, 2.75))
for k in MODEL_ORDER:
    accs = [DATA[k]["conditions"][c]["acc"] for c in COND_ORDER]
    ax.plot(range(len(COND_ORDER)), accs, marker="o", markersize=2.6,
            color=COLORS[k], label=SHORT[k], zorder=3)
ax.axvspan(4.5, 5.5, color="0.93", zorder=0)
ax.set_xticks(range(len(COND_ORDER)))
ax.set_xticklabels([COND_LABEL[c] for c in COND_ORDER])
ax.set_ylabel("Accuracy")
ax.set_ylim(0.42, 1.02)
ax.grid(axis="y", color="0.88", linewidth=0.5)
ax.set_axisbelow(True)
ax.legend(ncols=3, loc="upper center", bbox_to_anchor=(0.5, -0.34), frameon=False,
          handlelength=1.2, columnspacing=1.0)
save(fig, "fig_conditions")

# ------------------------------------------------ F4: resistance vs update
fig, ax = plt.subplots(figsize=(5.5, 3.1))
xs = np.linspace(0.0, 1.0, 400)
ys = np.linspace(0.0, 1.0, 400)
X, Y = np.meshgrid(xs, ys)
with np.errstate(divide="ignore", invalid="ignore"):
    EAS = np.where(X + Y > 0, 2 * X * Y / (X + Y), 0)
cs = ax.contour(X, Y, EAS, levels=[0.70, 0.80, 0.85, 0.90, 0.95],
                colors="0.75", linewidths=0.6, linestyles="--", zorder=1)
ax.clabel(cs, inline=True, fontsize=6.5, fmt="%.2f")
OFF4 = {  # annotation offsets (pt) to avoid collisions
    "gpt-5.6-terra": (4, -9), "muse": (4, 4), "gpt-5.6-luna": (-2, -10),
    "deepseek-chat": (4, 4), "qwen3.7-max": (4, 4), "qwen3.7-plus": (4, -9),
    "gpt-5.6-sol": (-4, -10), "grok": (4, 4),
}
OFF5 = {
    "muse": (3, -9), "qwen3.7-plus": (-3, -10), "gpt-5.6-terra": (3, 5),
    "grok": (-3, -10), "deepseek-chat": (3, 5), "gemini-3.7-fl": (-4, 6),
    "gpt-5.6-sol": (3, 5), "qwen3.7-max": (3, -9),
}
SHORT2 = {  # compact panel names for the calibration grid
    "deepseek-chat": "DeepSeek", "gpt-5.6-luna": "Luna", "qwen3.7-max": "Qwen Max",
    "qwen3.7-plus": "Qwen Plus", "gemini-3.7-fl": "Gemini 3.7",
    "gemini-3.5-lite": "Gemini 3.5L", "gpt-5.6-terra": "Terra", "muse": "Muse",
    "grok": "Grok 4.6", "gpt-5.6-sol": "Sol",
}
for k in MODEL_ORDER:
    cur = DATA[k]["cur"]
    res = 1.0 - DATA[k]["fbar"]
    ax.scatter(cur, res, color=COLORS[k], s=26, zorder=3)
    ox, oy = OFF4.get(k, (4, 3))
    ax.annotate(SHORT[k].replace("GPT-5.6 ", "").replace(" Spark 1.2", " Spark"),
                (cur, res), textcoords="offset points", xytext=(ox, oy), fontsize=6.8, zorder=3)
ax.set_xlim(0.70, 1.035)
ax.set_ylim(0.82, 1.012)
ax.set_xlabel("Correct update rate (CUR)")
ax.set_ylabel("Corruption resistance (1 - FBAR)")
ax.text(0.712, 0.997, "trust memory only", fontsize=6.8, color="0.45", style="italic")
ax.text(0.965, 0.832, "trust web only", fontsize=6.8, color="0.45", style="italic", ha="right")
save(fig, "fig_arbitration")

# ------------------------------------------------ F5: cost vs EAS
fig, ax = plt.subplots(figsize=(5.5, 3.0))
pts = {}
for k in MODEL_ORDER:
    cost100 = DATA[k]["cost"] * 100.0 / N_RUNS[k]
    pts[k] = (cost100, DATA[k]["eas"])
    ax.scatter(cost100, DATA[k]["eas"], color=COLORS[k], s=26, zorder=3)
    ox, oy = OFF5.get(k, (4, 3))
    ax.annotate(SHORT[k].replace("GPT-5.6 ", "").replace(" Spark 1.2", " Spark"),
                (cost100, DATA[k]["eas"]), textcoords="offset points",
                xytext=(ox, oy), fontsize=6.8, zorder=3)
# Pareto frontier: gemini-3.5-lite -> luna -> gemini-3.7-flash
front = sorted([("gemini-3.5-lite",), ("gemini-3.7-fl",)],
               key=lambda t: pts[t[0]][0])
fx = [pts[t[0]][0] for t in front]
fy = [pts[t[0]][1] for t in front]
ax.step(fx + [10], fy + [fy[-1]], where="post", color="0.55", linewidth=0.8,
        linestyle=":", zorder=2)
ax.set_xscale("log")
ax.set_xlabel("Estimated API cost per 100 runs (USD, list pricing)")
ax.set_ylabel("Epistemic Arbitration Score (EAS)")
ax.set_xlim(0.22, 12)
ax.set_ylim(0.82, 1.00)
ax.grid(axis="y", color="0.88", linewidth=0.5)
ax.set_axisbelow(True)
save(fig, "fig_cost")

# ------------------------------------------------ F6: failure taxonomy
# Source: analysis/cross_model_report.md, table 3 (per-episode prior/final taxonomy).
TAX = {  # model: (rescued, corrupted, stuck_wrong, correct_stable)
    "Gemini 3.7 Flash": (49, 1, 3, 47),
    "Qwen3.7 Max": (45, 3, 7, 45),
    "GPT-5.6 Luna": (42, 0, 10, 48),
    "GPT-5.6 Terra": (36, 0, 8, 36),
    "Muse Spark 1.2": (38, 1, 4, 34),
    "Qwen3.7 Plus": (43, 1, 9, 47),
    "GPT-5.6 Sol": (29, 0, 7, 14),
    "Grok 4.6": (37, 3, 7, 33),
    "DeepSeek V4 Flash": (30, 6, 13, 51),
    "Gemini 3.5 Flash-Lite": (46, 2, 6, 46),
}
CATS = ["correct and stable", "rescued", "corrupted", "stuck wrong"]
CAT_COLORS = ["#1f77b4", "#2ca02c", "#d62728", "#7f7f7f"]
fig, ax = plt.subplots(figsize=(5.5, 3.3))
ys = np.arange(len(TAX))[::-1]
lefts = np.zeros(len(TAX))
for ci, cat in enumerate(CATS):
    idx = 3 if cat == "correct and stable" else (0 if cat == "rescued" else (1 if cat == "corrupted" else 2))
    vals = np.array([TAX[m][["rescued", "corrupted", "stuck wrong", "correct and stable"].index(
        ["rescued", "corrupted", "stuck wrong", "correct and stable"][idx])] for m in TAX])
    tots = np.array([sum(v) for v in TAX.values()])
    fr = vals / tots
    ax.barh(ys, fr, left=lefts, color=CAT_COLORS[ci], label=cat, height=0.62,
            edgecolor="white", linewidth=0.4)
    lefts += fr
ax.set_yticks(ys)
ax.set_yticklabels([f"{m} (n={sum(TAX[m])})" for m in TAX], fontsize=7.5)
ax.set_xlim(0, 1)
ax.set_xlabel("Fraction of scored episodes")
ax.legend(ncols=4, loc="upper center", bbox_to_anchor=(0.5, -0.12), frameon=False,
          handlelength=1.1, columnspacing=1.0)
save(fig, "fig_taxonomy")

